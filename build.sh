progress() {
  local done=$1 total=$2 ok=$3 fail=$4 label=$5
  local pct=$(( done * 100 / total ))
  printf "\r%s: %d/%d (%d%%)  ok=%d fail=%d" "$label" "$done" "$total" "$pct" "$ok" "$fail"
}

